def main():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))

    for article, arabic_text in MISSING_ARABIC.items():
        if article not in data:
            raise KeyError(f"{article} not found in source JSON")

        old_value = data[article].get("arabic", "")

        if old_value:
            print(f"{article}: already has Arabic text; skipping")
            continue

        data[article]["arabic"] = arabic_text
        print(f"{article}: Arabic text restored")

    SOURCE.write_text(
        json.dumps(data, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    print("\nUpdated:", SOURCE)


if __name__ == "__main__":
    main()